#!/usr/bin/env python3
"""Render the machine-readable registries into Markdown pages.

The registries under registry/ are the source of truth; the pages written
here are views. Never edit a generated page by hand: change the registry and
run

    .venv/bin/python tools/gen_docs.py

tools/check_platform.py fails when a generated page is out of date.
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REG = ROOT / "registry"
BANNER = "<!-- Generated by tools/gen_docs.py from {src}. Do not edit; change the registry. -->"


def load(name):
    with open(REG / name, encoding="utf-8") as f:
        return yaml.safe_load(f)


def front(status, owner, src):
    return (
        "---\n"
        f"Status: {status}\n"
        "Doc-Type: generated\n"
        f"Owner: {owner}\n"
        f"Generated-From: {src}\n"
        "---\n\n"
        + BANNER.format(src=src)
        + "\n\n"
    )


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def ids(items):
    return ", ".join(items) if items else "none"


# ---------------------------------------------------------------- requirements

def requirement_table(items):
    out = ["| ID | Title | Pillars | Verified by | First gate |", "|---|---|---|---|---|"]
    for r in items:
        verified = ids(r.get("verified-by", []))
        if r.get("verified-by-other"):
            verified += "; " + r["verified-by-other"]
        out.append(
            f"| {r['id']} | {cell(r['title'])} | {', '.join(r.get('pillars', []))} "
            f"| {cell(verified)} | {cell(r['first-gate'])} |"
        )
    out.append("")
    return out


def requirement_statements(items, level):
    out = []
    for r in items:
        drift = ""
        if r.get("drift"):
            drift = f" Open drift: {', '.join(r['drift'])}."
        specified = r["specified-in"].rstrip(".")
        if not specified.startswith("Not yet"):
            specified = "Specified in " + specified
        out.append(f"{'#' * level} {r['id']} {r['title']}\n")
        out.append(f"{r['statement']}\n")
        out.append(f"Status: {r['status']}. Source: {r['source']}. {specified}.{drift}\n")
    return out


def product_requirements(req, qa):
    out = [front("Accepted", "product-owner", "registry/requirements.yaml")]
    out.append("# Product requirements\n")
    out.append(
        "The twelve product requirements every component must uphold, and the "
        "quality-attribute requirements that set how well it must uphold them. "
        "Each \"must\" or \"never\" in a contract or design document traces to "
        "one of these. R-series wording is verbatim from whitepaper draft 0.4 "
        "section 2 (S6), except where a requirement's Source line names the PDR "
        "that reworded it; the wording on this page is the normative one. The owner approved R1 to R12 with PDR-0001 on "
        "2026-11-07; changing one needs a PR the owner approves.\n"
    )
    out.extend(requirement_table(req))
    out.append("## Statements\n")
    out.extend(requirement_statements(req, 3))
    out.append("## Quality-attribute requirements\n")
    if qa:
        out.append(
            "QA requirements are grouped by pillar; the "
            "[quality attributes](quality-attributes.md) page shows which goals "
            "still lack one.\n"
        )
        out.extend(requirement_table(qa))
        out.extend(requirement_statements(qa, 3))
    else:
        out.append("None allocated.\n")
    return "\n".join(out)


def traceability(req, tests):
    by_t = {t["id"]: t for t in tests}
    out = [front("Proposed", "verification-lead", "registry/requirements.yaml, registry/tests.yaml")]
    out.append("# Traceability matrix\n")
    out.append(
        "Which conformance tests prove each requirement, at which stage, and "
        "which tests prove no requirement yet. A requirement with no test "
        "needs another stated method of verification; a test with no "
        "requirement is a trace gap for WP1 to resolve.\n"
    )
    out.append("## Requirement to test\n")
    out.append("| Requirement | Tests | Stages | Other verification |")
    out.append("|---|---|---|---|")
    for r in req:
        tids = r.get("verified-by", [])
        stages = sorted({by_t[t]["stage"] for t in tids if t in by_t})
        out.append(
            f"| {r['id']} {cell(r['title'])} | {ids(tids)} | {ids(stages)} "
            f"| {cell(r.get('verified-by-other', ''))} |"
        )
    gaps = [t for t in tests if not t.get("verifies")]
    out.append("")
    out.append("## Trace gaps\n")
    if gaps:
        out.append(
            f"{len(gaps)} of {len(tests)} tests verify no listed requirement. "
            "Draft 0.4 Appendix D did not map them.\n"
        )
        out.append("| Test | Title | Stage |")
        out.append("|---|---|---|")
        for t in gaps:
            out.append(f"| {t['id']} | {cell(t['title'])} | {t['stage']} |")
    else:
        out.append("None.")
    out.append("")
    return "\n".join(out)


def impl(t):
    # soul-conformance's status, plus component evidence where it exists.
    comp = t.get("component-tests") or []
    return t["implementation"] + (f"; component tests: {cell('; '.join(comp))}" if comp else "")


def conformance_catalog(tests):
    order = ["0", "1", "2a", "2b", "3", "4"]
    out = [front("Proposed", "verification-lead", "registry/tests.yaml")]
    out.append("# Conformance catalog\n")
    out.append(
        "What each conformance test must prove, grouped by the stage whose "
        "exit it gates. The platform owns these specifications; "
        "true-line/soul-conformance owns the executable suites and reports "
        "results against them.\n"
    )
    for stage in order:
        group = [t for t in tests if t["stage"] == stage]
        if not group:
            continue
        out.append(f"## Stage {stage}\n")
        out.append("| Test | Stimulus | Required observation | Verifies | Implementation |")
        out.append("|---|---|---|---|---|")
        for t in group:
            out.append(
                f"| {t['id']} {cell(t['title'])} | {cell(t['stimulus'])} | {cell(t['observation'])} "
                f"| {ids(t.get('verifies', []))} | {impl(t)} |"
            )
        out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- repositories

DISPOSITION_TEXT = {
    "keep": "Keep",
    "keep-and-split": "Keep and split",
    "designate": "Designate a new role",
    "merge-into-agent-bot": "Merge into agent-bot",
    "archive": "Archive",
    "decide": "Owner decision needed",
    "adjacent": "Adjacent, outside the product",
}


def repository_catalog(data):
    layers = {l["id"]: l["name"] for l in data["layers"]}
    repos = data["repos"]
    out = [front("Accepted", "product-owner", "registry/repos.yaml")]
    out.append("# Repository catalog\n")
    out.append(
        "Every repository that builds, specifies, verifies or operates the "
        "platform, with one purpose each and the disposition decided in "
        "PDR-0002. A repository exists only when it meets an admission "
        "criterion and owns at least one seam; anything else is a directory "
        "in an existing repository.\n"
    )
    out.append("## Admission criteria\n")
    for k, v in data["admission-criteria"].items():
        out.append(f"- **{k}** {v}")
    out.append("")
    out.append("## Summary\n")
    out.append("| Repository | Layer | Status | Disposition | Purpose |")
    out.append("|---|---|---|---|---|")
    for r in repos:
        out.append(
            f"| {r['org']}/{r['name']} | {layers[r['layer']]} | {r['status']} "
            f"| {DISPOSITION_TEXT[r['disposition']]} | {cell(r['purpose'])} |"
        )
    out.append("")
    for layer_id, layer_name in layers.items():
        group = [r for r in repos if r["layer"] == layer_id and r.get("owns")]
        if not group:
            continue
        out.append(f"## {layer_name}\n")
        for r in group:
            out.append(f"### {r['name']}\n")
            bits = [f"Criteria: {ids(r.get('criteria', []))}"]
            if r.get("trust-domain"):
                bits.append(f"trust domain: {r['trust-domain']}")
            if r.get("work-packages"):
                bits.append(f"work packages: {ids(r['work-packages'])}")
            out.append("; ".join(bits) + ".\n")
            out.append("Owns: " + "; ".join(r["owns"]) + ".\n")
            if r.get("must-not-own"):
                out.append("Must not own: " + "; ".join(r["must-not-own"]) + ".\n")
            if r.get("follow-up"):
                out.append(f"Follow-up: {r['follow-up']}\n")
    rest = [r for r in repos if r.get("rationale") and not r.get("owns")]
    if rest:
        out.append("## Repositories to merge, archive or leave outside the product\n")
        out.append("| Repository | Disposition | Rationale |")
        out.append("|---|---|---|")
        for r in rest:
            out.append(f"| {r['name']} | {DISPOSITION_TEXT[r['disposition']]} | {cell(r['rationale'])} |")
        out.append("")
    out.append("## Governance repositories\n")
    out.append("Linked from the platform, never copied into it.\n")
    out.append("| Repository | Role |")
    out.append("|---|---|")
    for g in data["governance"]:
        out.append(f"| {g['org']}/{g['name']} | {cell(g['role'])} |")
    out.append("")
    return "\n".join(out)


def seams_doc(data):
    seams = data["seams"]
    out = [front("Proposed", "protocol-maintainer", "registry/seams.yaml")]
    out.append("# Seams\n")
    out.append(
        "The interfaces between repositories and where each contract lives. "
        "A seam is the only legitimate coupling between two repositories. "
        "Seams whose contract exists only as a plan or as repo-local prose "
        "are the likeliest place for two implementations to drift.\n"
    )
    out.append("| Seam | Provider | Consumers | Contract home | Status |")
    out.append("|---|---|---|---|---|")
    for s in seams:
        out.append(
            f"| `{s['id']}` {cell(s['name'])} | {s['provider']} | {ids(s.get('consumers', []))} "
            f"| {cell(s['contract-home'])} | {s['contract-status']} |"
        )
    out.append("")
    out.append("## Notes\n")
    for s in seams:
        extra = []
        if s.get("requirements"):
            extra.append("requirements " + ids(s["requirements"]))
        if s.get("drift"):
            extra.append("drift " + ids(s["drift"]))
        if s.get("note"):
            extra.append(s["note"])
        if extra:
            out.append(f"- `{s['id']}`: " + "; ".join(extra))
    out.append("")
    return "\n".join(out)


def identifiers_doc(data):
    out = [front("Proposed", "platform-maintainer", "registry/ids.yaml")]
    out.append("# Identifiers\n")
    out.append(
        "Every identifier a platform document may cite, its single meaning, "
        "and the registry that resolves it. The checker rejects undeclared "
        "IDs and retired labels in controlled documents.\n"
    )
    out.append("## Platform namespaces\n")
    out.append("| Prefix | Meaning | Resolves in | Allocation |")
    out.append("|---|---|---|---|")
    for n in data["namespaces"]:
        out.append(
            f"| {n['prefix']} | {cell(n['meaning'])} | `{n['registry']}` | {cell(n['allocation'])} |"
        )
    out.append("")
    out.append("## Identifiers owned elsewhere\n")
    out.append("| Prefix | Owner | Rule |")
    out.append("|---|---|---|")
    for n in data["foreign"]:
        out.append(f"| {n['prefix']} | {n['owner']} | {cell(n['meaning'])} |")
    out.append("")
    out.append("## Retired labels\n")
    out.append("| Label | Write instead | Why |")
    out.append("|---|---|---|")
    for n in data["retired"]:
        out.append(f"| {cell(n['label'])} | {cell(n['use'])} | {cell(n['reason'])} |")
    out.append("")
    return "\n".join(out)


def render_all():
    reqs = load("requirements.yaml")
    req, qa = reqs["requirements"], reqs.get("quality-attributes", [])
    tests = load("tests.yaml")["tests"]
    pages = {
        "docs/02-requirements/product-requirements.md": product_requirements(req, qa),
        "docs/02-requirements/traceability-matrix.md": traceability(req + qa, tests),
        "docs/07-verification/conformance-catalog.md": conformance_catalog(tests),
        "docs/03-architecture/repository-catalog.md": repository_catalog(load("repos.yaml")),
        "docs/03-architecture/seams.md": seams_doc(load("seams.yaml")),
        "docs/00-governance/identifiers.md": identifiers_doc(load("ids.yaml")),
    }
    return {rel: re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n" for rel, text in pages.items()}


def main():
    for rel, text in render_all().items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("wrote", rel)


if __name__ == "__main__":
    sys.exit(main())
